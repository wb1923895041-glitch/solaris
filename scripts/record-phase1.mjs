import {chromium} from 'playwright';
import fs from 'node:fs/promises';
const output='output/playwright/phase-1/phase1-continuous-demo.webm';
const browser=await chromium.launch({channel:'chrome',headless:true});
const context=await browser.newContext({viewport:{width:2560,height:1440},recordVideo:{dir:'output/playwright/phase-1/video-work',size:{width:1280,height:720}}});
const page=await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:4173');await page.waitForFunction(()=>window.solarisQA);
const demo=await fs.readFile('scripts/browser-phase1-demo.js','utf8');
const action=(0,eval)('('+demo+')');
const result=await action(page);
const video=page.video();await context.close();
await video.saveAs(output);
const stat=await fs.stat(output);if(stat.size<10000)throw new Error('Video empty or incomplete');
const verifyContext=await browser.newContext();const verifyPage=await verifyContext.newPage();
await verifyPage.goto('http://127.0.0.1:5173/output/playwright/phase-1/phase1-continuous-demo.webm');
await verifyPage.waitForSelector('video');
await verifyPage.evaluate(()=>document.querySelector('video').load());
await verifyPage.waitForFunction(()=>document.querySelector('video').readyState>=2);
const metadata=await verifyPage.evaluate(()=>{const v=document.querySelector('video');return{durationSeconds:v.duration,width:v.videoWidth,height:v.videoHeight};});
await verifyPage.evaluate(()=>document.querySelector('video').play());await verifyPage.waitForTimeout(2000);
const played=await verifyPage.evaluate(()=>document.querySelector('video').currentTime);
if(metadata.durationSeconds<30||played<1||errors.length)throw new Error('Video verification failed: '+JSON.stringify({metadata,played,errors}));
await fs.writeFile('docs/phase-1/recording-report.json',JSON.stringify({output,bytes:stat.size,...metadata,decodedPlaybackSeconds:played,errors,actions:result,method:'Playwright context.recordVideo; context closed and saved, then video decoded/played in Chrome'},null,2)+'\n');
await browser.close();console.log(JSON.stringify({output,bytes:stat.size,...metadata,decodedPlaybackSeconds:played,actions:result}));
